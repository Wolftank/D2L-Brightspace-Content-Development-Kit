import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('download opens the SCORM guide with keyboard containment, focus return, and saved instructions', async ({ page }) => {
  test.setTimeout(60_000);
  await page.goto('/?new=1');
  await page.getByLabel('Project title').fill('D2L guide');
  await page.getByLabel('What should students learn or do?').fill('Create a quiz');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  const download = page.getByRole('link', { name: 'Download SCORM package' });
  await expect(download).toBeVisible({ timeout: 15_000 });
  const packageDownload = page.waitForEvent('download');
  await download.click();
  expect((await packageDownload).suggestedFilename()).toMatch(/\.zip$/);
  const guide = page.getByRole('dialog', { name: 'Add to D2L' });
  await expect(guide).toBeVisible();
  const close = guide.getByRole('button', { name: 'Close instructions' });
  await expect(guide.getByRole('heading', { name: 'Add to D2L', level: 2 })).toBeFocused();
  await expect(guide.locator('ol > li')).toHaveCount(5);
  await expect(guide.getByRole('heading', { name: 'Open your course' })).toBeInViewport();
  await page.keyboard.press('Shift+Tab');
  await expect(close).toBeFocused();
  const save = guide.getByRole('link', { name: 'Save instructions as text' });
  await save.focus();
  await page.keyboard.press('Tab');
  await expect(close).toBeFocused();
  await page.keyboard.press('Tab');
  const firstHelpLink = guide.getByRole('navigation', { name: 'D2L help' }).getByRole('link').first();
  await expect(firstHelpLink).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(close).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(guide).not.toBeVisible();
  await expect(download).toBeFocused();
  const reopen = page.getByRole('button', { name: 'Add to D2L instructions' });
  await reopen.click();
  await expect(guide).toBeVisible();
  const textDownload = page.waitForEvent('download');
  await save.click();
  const text = await textDownload;
  expect(text.suggestedFilename()).toBe('deploy.txt');
  expect(await readFile(await text.path(), 'utf8')).toContain('Complete the activity');
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await close.click();
  await expect(reopen).toBeFocused();
});

test('guide fits a phone viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/?new=1');
  await page.getByLabel('Project title').fill('Mobile guide');
  await page.getByLabel('What should students learn or do?').fill('Create a quiz');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.getByRole('button', { name: 'Add to D2L instructions' }).click({ timeout: 15_000 });
  const guide = page.getByRole('dialog');
  expect(await guide.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.keyboard.press('Escape');
  await expect(guide).not.toBeVisible();
});
