import { expect, test } from '@playwright/test';

test('interface copy audit across empty, running, ready, guide, and failed states', async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/?new=1');
  await expect(page.getByRole('heading', { level: 1, name: 'Create an activity' })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Design', exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Build', exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Preview' })).toHaveCount(0);
  await expect(page.getByText('Local mode', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Course material workspace', { exact: true })).toBeVisible();
  const title = await page.getByRole('heading', { level: 1 }).boundingBox();
  const design = await page.getByRole('region', { name: 'Design', exact: true }).boundingBox();
  const heading = await page.getByRole('heading', { name: 'Design', exact: true }).boundingBox();
  const firstLabel = await page.getByText('Project title', { exact: true }).boundingBox();
  const send = await page.getByRole('button', { name: 'Send', exact: true }).boundingBox();
  expect(design!.y - (title!.y + title!.height)).toBeLessThanOrEqual(24);
  expect(firstLabel!.y - (heading!.y + heading!.height)).toBeLessThanOrEqual(20);
  expect(design!.y + design!.height - (send!.y + send!.height)).toBeLessThanOrEqual(28);
  await expect(page.getByRole('group', { name: 'Conversation history' })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('empty.png'), fullPage: true });
  await page.getByLabel('Project title').fill('Cell division practice');
  await page.getByLabel('What should students learn or do?').fill('Create a practice quiz.');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.getByText('Project:', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Request progress')).toContainText('Building from the SCORM starter');
  await expect(page.getByRole('button', { name: 'Working…' })).toBeDisabled();
  await expect(page.getByLabel('Describe a change')).toHaveAccessibleName('Describe a change');
  await expect(page.locator('label[for="request-text"]')).toHaveClass('sr-only');
  await page.screenshot({ path: testInfo.outputPath('running.png'), fullPage: true });
  await expect(page.getByRole('heading', { name: 'Ready to download' })).toBeVisible({ timeout: 15_000 });
  await expect(page.getByText('Request complete', { exact: true })).toBeVisible();
  await expect(page.getByTitle('Interactive preview of build 1')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('ready.png'), fullPage: true });
  await expect(page.getByLabel('Describe a change')).toBeEditable();
  await page.getByRole('button', { name: 'Add to D2L instructions' }).click();
  await expect(page.getByRole('dialog', { name: 'Add to D2L' })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('guide.png'), fullPage: true });
  await page.keyboard.press('Escape');
  await page.evaluate(() => sessionStorage.clear());
  await page.goto('/?new=1');
  await page.getByLabel('Project title').fill('Cell division practice');
  await page.getByLabel('What should students learn or do?').fill('[qa-fail] Create a practice quiz.');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'QA needs attention' })).toBeVisible({ timeout: 15_000 });
  await expect(page.getByText('Request complete', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('qa-failed.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: testInfo.outputPath('qa-failed-phone.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
